from esum.core.docs import NO_QUIRKS, doc_path, extract_quirks, render_site_doc, site_doc, write_site_doc
from esum.core import docs
from pathlib import Path
import tomllib

import pytest


def test_generated_doc_contents(example_registry):
    text = render_site_doc(example_registry.get("demo"))
    assert text.startswith("<!-- esum:generated by `esum docs demo --write`")
    for snippet in ("# demo", "Demo forum for tests", "- **Engine:** standalone module",
                    "- **Transport:** T1 direct HTTP", "- **Module format:** 1",
                    "- **Ported from:** tests only", "### `thread`", "Tier 0 (read) · from the site",
                    "esum demo thread --id <int> [--mode medium|full]",
                    "| `--id` | int | required | Topic id. |",
                    "| `--mode` | medium\\|full | `'medium'` | medium (head + tail) or full. |",
                    "### `bookmark`", "Tier 1 (reversible write, ask the user first)",
                    "## Quirks", NO_QUIRKS):
        assert snippet in text, snippet
    one = render_site_doc(example_registry.get("one"))
    assert "### `topic`" in one and "from the demoeng engine" in one and "### `extra`" in one
    assert not any(line != line.rstrip() for line in text.splitlines())


def test_quirks_are_preserved_on_regeneration(example_registry):
    demo = example_registry.get("demo")
    path = write_site_doc(demo)
    assert path == doc_path(demo) == demo.source.parent / "doc.md"
    edited = path.read_text(encoding="utf-8").replace(
        NO_QUIRKS, "- The API caps pages at 20.\n\n### Sub-heading kept")
    path.write_text(edited.replace("Demo forum for tests", "stale label"), encoding="utf-8")
    write_site_doc(demo)
    text = path.read_text(encoding="utf-8")
    assert "stale label" not in text and "Demo forum for tests" in text
    assert extract_quirks(text) == "- The API caps pages at 20.\n\n### Sub-heading kept"
    assert site_doc(demo) == text


def test_extract_quirks_stops_at_next_section():
    assert extract_quirks("# x\n## Quirks\nA\n## Other\nB") == "A"
    assert extract_quirks("no section") is None
    assert extract_quirks(None) is None


def test_builtin_doc_path_is_beside_the_module(example_registry):
    one = example_registry.get("one")
    path = doc_path(one)
    assert path == one.source.parent / "doc.md"
    assert path.as_posix().endswith("esumtest_sites/demoeng/one/doc.md")


def test_markdown_site_doc_is_itself(example_registry):
    notes = example_registry.get("notes")
    assert site_doc(notes).startswith("---\nname: notes")
    assert write_site_doc(notes) == notes.source


