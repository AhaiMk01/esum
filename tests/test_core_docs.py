REPO = Path(__file__).resolve().parents[1]


def test_wheel_ships_builtin_site_docs():
    # Each doc.md is a file of the esum package, beside its module; no separate mapping is needed.
    config = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))
    wheel = config["tool"]["hatch"]["build"]["targets"]["wheel"]
    assert wheel["packages"] == ["src/esum"] and "force-include" not in wheel
    assert not any("doc.md" in pattern for pattern in wheel.get("exclude", []))
    assert wheel["exclude"] == ["src/esum/sites/**/tests/"]   # a site's tests and fixtures stay out


def test_installed_doc_keeps_quirks(monkeypatch, example_registry):
    # Simulate a wheel install: no checkout; the doc is read from beside the installed module.
    site = example_registry.get("one")   # built-in-style; its doc.md ships beside its module
    (site.source.parent / "doc.md").write_text(render_site_doc(site, "- A hand-written quirk."), encoding="utf-8")
    monkeypatch.setattr(docs, "repo_root", lambda: None)
    path = docs.doc_path(site)
    assert path == site.source.parent / "doc.md" and path.is_file()
    quirks = docs.extract_quirks(path.read_text(encoding="utf-8"))
    assert quirks and quirks != docs.NO_QUIRKS
    text = docs.site_doc(site)
    assert quirks in text and docs.NO_QUIRKS not in text
    with pytest.raises(RuntimeError, match="source checkout"):
        docs.write_site_doc(site)
